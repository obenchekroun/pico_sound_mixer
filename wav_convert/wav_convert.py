#!/usr/bin/env python3
# wav_convert.py
# rev 1 - shabaz - Jan 2024
# rev 2 - Oct 2026 - format checks, sounds.h / sounds_table.c generation
#
# Scans a folder for .wav files and converts each one to a C array.
# Also generates:
#   sounds.h        enum of sound ids, extern declarations, table declarations
#   sounds_table.c  sound_array[] and sound_array_len[] definitions
#
# Every .wav must be mono, 16-bit PCM, at the firmware sample rate (24000 Hz
# by default). Any file that does not match stops the run with an error, so a
# bad file can never end up playing at the wrong pitch on the board.
#
# Usage, from any directory:
#   python3 wav_convert.py                  # wav_files/ -> output/
#   python3 wav_convert.py -o ../sounds     # write straight into the firmware
#   python3 wav_convert.py --rate 22050

import argparse
import os
import re
import struct
import sys
import wave

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
SAMPLES_PER_LINE = 16


def c_identifier(stem):
    """Turn a file stem into a valid C identifier (lowercase)."""
    ident = re.sub(r"[^0-9a-zA-Z_]", "_", stem).lower()
    if not ident or ident[0].isdigit():
        ident = "s_" + ident
    return ident


def check_format(path, wav, rate):
    problems = []
    if wav.getnchannels() != 1:
        problems.append("%d channels (must be mono)" % wav.getnchannels())
    if wav.getsampwidth() != 2:
        problems.append("%d-bit samples (must be 16-bit)" % (wav.getsampwidth() * 8))
    if wav.getframerate() != rate:
        problems.append("%d Hz (must be %d Hz)" % (wav.getframerate(), rate))
    if wav.getcomptype() != "NONE":
        problems.append("compressed (%s), must be PCM" % wav.getcomptype())
    if problems:
        sys.exit("ERROR: %s: %s" % (os.path.basename(path), "; ".join(problems)))


def convert_file(path, out_dir, rate):
    """Convert one .wav to a .c file. Returns (identifier, sample count)."""
    stem = os.path.splitext(os.path.basename(path))[0]
    ident = c_identifier(stem)
    with wave.open(path, "r") as wav:
        check_format(path, wav, rate)
        nframes = wav.getnframes()
        samples = struct.unpack("<%dh" % nframes, wav.readframes(nframes))

    with open(os.path.join(out_dir, ident + ".c"), "w") as out:
        out.write("// generated by wav_convert.py from %s, do not edit\n" % os.path.basename(path))
        out.write("#include <stdint.h>\n")
        out.write("const int16_t %s[%d] = {\n" % (ident, nframes))
        for i in range(0, nframes, SAMPLES_PER_LINE):
            out.write("    " + ",".join(str(s) for s in samples[i:i + SAMPLES_PER_LINE]) + ",\n")
        out.write("};\n")
    return ident, nframes


def write_header(out_dir, sounds, rate):
    with open(os.path.join(out_dir, "sounds.h"), "w") as h:
        h.write("// generated by wav_convert.py, do not edit\n")
        h.write("#ifndef SOUNDS_H\n#define SOUNDS_H\n\n#include <stdint.h>\n\n")
        h.write("#define SOUND_SAMPLE_RATE %d\n" % rate)
        h.write("#define NUM_SOUNDS %d\n\n" % len(sounds))
        h.write("// sound ids, usable as index into sound_array[] and sound_array_len[]\n")
        h.write("enum sound_id {\n")
        for ident, _ in sounds:
            h.write("    %s,\n" % ident.upper())
        h.write("};\n\n")
        for ident, n in sounds:
            h.write("extern const int16_t %s[%d];\n" % (ident, n))
        h.write("\nextern const int16_t *const sound_array[NUM_SOUNDS];\n")
        h.write("extern const uint32_t sound_array_len[NUM_SOUNDS];\n")
        h.write("\n#endif // SOUNDS_H\n")


def write_table(out_dir, sounds):
    with open(os.path.join(out_dir, "sounds_table.c"), "w") as c:
        c.write("// generated by wav_convert.py, do not edit\n")
        c.write('#include "sounds.h"\n\n')
        c.write("const int16_t *const sound_array[NUM_SOUNDS] = {\n")
        for ident, _ in sounds:
            c.write("    %s,\n" % ident)
        c.write("};\n\n")
        c.write("const uint32_t sound_array_len[NUM_SOUNDS] = {\n")
        for ident, n in sounds:
            c.write("    %d, // %s\n" % (n, ident))
        c.write("};\n")


def main():
    parser = argparse.ArgumentParser(description="Convert .wav files to C arrays for the Pico sound mixer.")
    parser.add_argument("-i", "--input", default=os.path.join(SCRIPT_DIR, "wav_files"),
                        help="folder containing the .wav files (default: wav_files next to this script)")
    parser.add_argument("-o", "--output", default=os.path.join(SCRIPT_DIR, "output"),
                        help="folder for the generated .c/.h files (default: output next to this script)")
    parser.add_argument("--rate", type=int, default=24000,
                        help="required sample rate in Hz, must match the firmware (default: 24000)")
    args = parser.parse_args()

    files = sorted(f for f in os.listdir(args.input) if f.lower().endswith(".wav"))
    if not files:
        sys.exit("ERROR: no .wav file found in %s" % args.input)
    os.makedirs(args.output, exist_ok=True)

    sounds = []
    seen = {}
    for name in files:
        print("Processing " + name)
        ident, n = convert_file(os.path.join(args.input, name), args.output, args.rate)
        if ident in seen:
            sys.exit("ERROR: %s and %s both map to identifier '%s'" % (seen[ident], name, ident))
        seen[ident] = name
        sounds.append((ident, n))

    write_header(args.output, sounds, args.rate)
    write_table(args.output, sounds)

    total = sum(n for _, n in sounds)
    print("\nDone: %d sounds, %d samples, %.1f s of audio, %d bytes of flash"
          % (len(sounds), total, total / args.rate, total * 2))
    print("Generated in %s: sounds.h, sounds_table.c and one .c per sound" % args.output)


if __name__ == "__main__":
    main()
